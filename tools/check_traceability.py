#!/usr/bin/env python3
"""Requirement traceability gate.

Reads the requirement IDs from docs/REQUIREMENTS.md, collects the `REQ <ID> ...` tags that tests carry
(app: app/src/test and app/src/androidTest; web: ~/dev/QuizWeb/tests) and fails when
  * a requirement has no tagged test, or
  * a tag names a requirement that does not exist.
Writes docs/TRACEABILITY.md (requirement -> test files) so the matrix is always current.
"""
import os, re, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
web = os.environ.get("QUIZWEB", os.path.expanduser("~/dev/QuizWeb"))
req_text = open(os.path.join(root, "docs/REQUIREMENTS.md"), encoding="utf-8").read()
reqs = re.findall(r"^\| ([A-Z]{2}-\d+) \| (.+?) \|", req_text, re.M)
ids = [i for i, _ in reqs]

tag_line = re.compile(r"^\s*(?://|\*|/\*\*)\s*REQ ((?:[A-Z]{2}-\d+[ ,]*)+)", re.M)
found = {i: [] for i in ids}
unknown = []
for base, label in ((os.path.join(root, "app/src/test"), "app"), (os.path.join(root, "app/src/androidTest"), "device"),
                    (os.path.join(web, "tests"), "web")):
    for d, _, files in os.walk(base):
        for f in files:
            if not f.endswith((".kt", ".js")):
                continue
            path = os.path.join(d, f)
            text = open(path, encoding="utf-8").read()
            for m in tag_line.finditer(text):
                for tag in re.findall(r"[A-Z]{2}-\d+", m.group(1)):
                    name = f"{label}:{f}"
                    if tag not in found:
                        unknown.append(f"{name} names unknown requirement {tag}")
                    elif name not in found[tag]:
                        found[tag].append(name)

lines = ["# Traceability matrix", "", "Generated by `tools/check_traceability.py`; do not edit.", "",
         "| Requirement | Verified by |", "|---|---|"]
for i, text in reqs:
    lines.append(f"| {i} {text[:70]}{'…' if len(text) > 70 else ''} | {', '.join(sorted(found[i])) or '**none**'} |")
open(os.path.join(root, "docs/TRACEABILITY.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")

missing = [i for i in ids if not found[i]]
for m in missing:
    print(f"requirement {m} has no test")
for u in unknown:
    print(u)
if missing or unknown:
    sys.exit(1)
print(f"traceability ok: {len(ids)} requirements, all covered by tagged tests")
