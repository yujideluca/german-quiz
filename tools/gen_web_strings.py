#!/usr/bin/env python3
"""Writes the web version's src/strings.js from the app's string resources (the single source of the UI text).

    python3 tools/gen_web_strings.py [~/dev/QuizWeb/src/strings.js]

Android's %1$s / %1$d placeholders become {0}, {1}, ...; plurals become <name>_one / <name>_other. The update popup, update and
backup strings are Android-only and skipped; the few web-only texts are defined below.
"""
import json, os, re, sys
import xml.etree.ElementTree as ET

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
res = os.path.join(root, "app/src/main/res")
target = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/dev/QuizWeb/src/strings.js")
FOLDERS = {"en": "values", "de": "values-de", "pt": "values-pt", "es": "values-es"}
SKIP = re.compile(r"^(update_|prompt_|backup_(?!title))")

# Web-only texts: (en, de, pt, es)
EXTRA = {
    "aria_prev_month": ("Previous month", "Vorheriger Monat", "Mês anterior", "Mes anterior"),
    "aria_next_month": ("Next month", "Nächster Monat", "Próximo mês", "Mes siguiente"),
    "aria_more": ("More", "Mehr", "Mais", "Más"),
    "web_backup_explain": ("Progress is stored on this device only. Save a backup file to move it to another device or keep it safe.", "Der Fortschritt wird nur auf diesem Gerät gespeichert. Speichere eine Sicherungsdatei, um ihn auf ein anderes Gerät zu übertragen oder sicher aufzubewahren.", "O progresso é guardado somente neste dispositivo. Salve um arquivo de backup para levá-lo a outro dispositivo ou mantê-lo seguro.", "El progreso se guarda solo en este dispositivo. Guarda un archivo de copia para pasarlo a otro dispositivo o mantenerlo a salvo."),
    "web_backup_save": ("Save backup file", "Sicherungsdatei speichern", "Salvar arquivo de backup", "Guardar archivo de copia"),
    "web_backup_restore": ("Restore from backup file", "Aus Sicherungsdatei wiederherstellen", "Restaurar de um arquivo de backup", "Restaurar desde un archivo de copia"),
    "web_backup_restored": ("Backup restored.", "Sicherung wiederhergestellt.", "Backup restaurado.", "Copia restaurada."),
    "web_read_failed": ("Could not read that file.", "Diese Datei konnte nicht gelesen werden.", "Não foi possível ler esse arquivo.", "No se pudo leer ese archivo."),
    "web_load_failed": ("Could not load the vocabulary. Check your connection and reload.", "Die Vokabeln konnten nicht geladen werden. Prüfe deine Verbindung und lade die Seite neu.", "Não foi possível carregar o vocabulário. Verifique sua conexão e recarregue.", "No se pudo cargar el vocabulario. Comprueba tu conexión y recarga."),
}

def clean(text):
    text = text.replace("\\'", "'").replace("\\@", "@").replace("\\?", "?")
    return re.sub(r"%(\d+)\$[sd]", lambda m: "{" + str(int(m.group(1)) - 1) + "}", text)

out = {}
for lang, folder in FOLDERS.items():
    table = {}
    tree = ET.parse(os.path.join(res, folder, "strings.xml")).getroot()
    for el in tree.findall("string"):
        table[el.get("name")] = clean(el.text or "")
    for el in tree.findall("plurals"):
        for item in el.findall("item"):
            table[f'{el.get("name")}_{item.get("quantity")}'] = clean(item.text or "")
    out[lang] = table
# language names are not translated, so only the English file declares them
for lang in ("de", "pt", "es"):
    for key, value in out["en"].items():
        if key.startswith("language_name_"): out[lang][key] = value
for i, lang in enumerate(FOLDERS):
    for key, values in EXTRA.items(): out[lang][key] = values[i]

lines = ["// UI text per language, generated by tools/gen_web_strings.py in the Android project from res/values*/strings.xml",
         "// plus the few web-only texts. {0}, {1} ... are placeholders. English is the fallback for anything missing.",
         "export const STRINGS = {"]
for lang, table in out.items():
    lines.append(f"  {lang}: {{")
    for key, value in table.items():
        if SKIP.match(key): continue
        lines.append(f"    {key}: {json.dumps(value, ensure_ascii=False)},")
    lines.append("  },")
lines.append("};")
open(target, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("wrote", target, {lang: sum(1 for k in t if not SKIP.match(k)) for lang, t in out.items()})
