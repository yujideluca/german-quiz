package dev.yuji.quiz.data

import android.content.Context
import dev.yuji.quiz.content.ErrorSentenceEntry
import dev.yuji.quiz.content.NounEntry
import dev.yuji.quiz.content.PrepositionEntry
import dev.yuji.quiz.content.VerbEntry
import dev.yuji.quiz.content.parseErrorSentences
import dev.yuji.quiz.content.parseNouns
import dev.yuji.quiz.content.parsePrepositions
import dev.yuji.quiz.content.parseVerbs

interface VocabularySource {
    fun nouns(): List<NounEntry>
    fun prepositions(): List<PrepositionEntry>
    fun verbs(): List<VerbEntry>
    fun errorSentences(): List<ErrorSentenceEntry>
}

/** Reads nouns.json, prepositions.json, verbs.json and errors.json from assets/vocab (generated by tools/build_vocab.py). */
class AssetVocabularySource(private val context: Context) : VocabularySource {
    private fun read(name: String) = context.assets.open("vocab/$name").bufferedReader().use { it.readText() }
    override fun nouns() = parseNouns(read("nouns.json"))
    override fun prepositions() = parsePrepositions(read("prepositions.json"))
    override fun verbs() = parseVerbs(read("verbs.json"))
    override fun errorSentences() = parseErrorSentences(read("errors.json"))
}
